function assignPhotoName(item, folder, records, previous) {
  const automatic = item.nameAutoGenerated === true || !String(item.name || '').trim();
  if (!automatic) return Object.assign(item, { nameAutoGenerated: false, albumSequence: Number(previous && previous.albumSequence) || 0 });
  if (previous && previous.folderId === item.folderId && previous.nameAutoGenerated && previous.albumSequence > 0 && previous.name) {
    return Object.assign(item, { name: previous.name, title: previous.name, nameAutoGenerated: true, albumSequence: previous.albumSequence });
  }
  const name = String(folder.name || '回忆集').trim();
  const photos = records.filter(record => record.kind === 'photo' && record.payload && record.payload.folderId === item.folderId && record.contentId !== item.id);
  let maximum = new Set(photos.map(record => record.contentId)).size;
  photos.forEach(record => {
    const photo = record.payload, sequence = Number(photo.albumSequence);
    if (Number.isSafeInteger(sequence) && sequence > maximum) maximum = sequence;
    const text = String(photo.name || '');
    const suffix = text.slice(name.length), number = Number(suffix);
    if (text.startsWith(name) && /^\d+$/.test(suffix) && Number.isSafeInteger(number)) maximum = Math.max(maximum, number);
  });
  const sequence = maximum + 1;
  if (!Number.isSafeInteger(sequence)) throw new Error('相册图片编号已达到上限');
  const title = `${name}${sequence}`;
  return Object.assign(item, { name: title, title, nameAutoGenerated: true, albumSequence: sequence });
}
module.exports = { assignPhotoName };
