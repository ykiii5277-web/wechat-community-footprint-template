// 相册编辑页：新建时可一次上传多张图片；编辑已有图片时仍保持单张替换。
const data = require('../../utils/data');
const nav = require('../../utils/nav');
const cloud = require('../../utils/cloud-service');
const privacy = require('../../utils/privacy');

Page({
  data: { id: '', context: {}, folderId: '', folderName: '', images: [], canAddImages: true, name: '', showName: false, visibilityOptions: [], visibilityIndex: 1, visibilityName: '仅好友可见', visibilityHint: '', isPublic: false, hideUid: false },
async onLoad(options) { await require('../../utils/actions').ready();
    let photo = options.id ? data.getPhoto(options.id) : null;
    const routeContext = nav.contextFrom(options);
    const context = photo ? { campId: photo.campId || routeContext.campId, stageId: photo.stageId || routeContext.stageId, subcampId: photo.subcampId || routeContext.subcampId, activityName: photo.activityName || routeContext.activityName || '' } : routeContext;
    // 读取一次相册列表会把旧版未归类照片迁移到“回忆集”。
    data.getFolders(context);
    if (photo) photo = data.getPhoto(photo.id);
    const folderId = (photo && photo.folderId) || options.folderId || '';
    const folder = folderId ? data.getFolder(folderId) : null;
    if (!folder) {
      wx.showToast({ title: '请先进入一个相册再上传', icon: 'none' });
      return setTimeout(() => wx.navigateBack({ delta: 1 }), 250);
    }
    const albumContext = { campId: folder.campId || context.campId, stageId: folder.stageId || '', subcampId: folder.subcampId || '', activityName: folder.activityName || '' };
    const visibilityOptions = data.visibilityOptions();
    const visibilityIndex = Math.max(0, visibilityOptions.findIndex(item => item.value === (photo ? photo.visibility : 'friends')));
    const images = photo && photo.image ? [photo.image] : [];
    this._originalPhotoName = photo ? photo.name : '';
    this._originalAutoName = !!(photo && photo.nameAutoGenerated);
    this.setData({ id: photo ? photo.id : '', context: albumContext, folderId, folderName: folder.name || '回忆集', images, canAddImages: true, name: photo ? photo.name : '', showName: photo ? photo.showName === true : false, visibilityOptions, visibilityIndex, visibilityName: visibilityOptions[visibilityIndex].name, visibilityHint: visibilityOptions[visibilityIndex].hint, isPublic: visibilityOptions[visibilityIndex].value === 'public', hideUid: photo ? photo.hideUid === true : false });
  },
  input(e) { this.setData({ [e.currentTarget.dataset.field]: e.detail.value }); },
  nameVisible(e) { this.setData({ showName: e.detail.value }); },
  visibilityChange(e) { const visibilityIndex = Number(e.detail.value); const visibility = this.data.visibilityOptions[visibilityIndex]; this.setData({ visibilityIndex, visibilityName: visibility.name, visibilityHint: visibility.hint, isPublic: visibility.value === 'public' }); },
  hideUidChange(e) { this.setData({ hideUid: e.detail.value }); },
  previewImage(e) { return require('../../utils/image-preview').open(this.data.images, e.currentTarget.dataset.index); },
  chooseImages() {
    if (this._busy) return;
    privacy.chooseMedia({ count: this.data.id ? 1 : 20, preferMedia: true, mediaType: ['image'], success: async result => {
      if (this._busy) return;
      this._busy = true;
      wx.showLoading({ title: '正在压缩上传', mask: true });
      try {
        const paths = result.tempFiles.map(file => file.tempFilePath);
        await cloud.persistImages(paths, 'photos', images => {
          this.setData({ images: this.data.id ? images.slice(0, 1) : this.data.images.concat(images), canAddImages: true });
        });
      } catch (error) {
        cloud.showUploadError(error, '照片上传失败');
      } finally { this._busy = false; wx.hideLoading(); }
    }, fail: privacy.showChooseImageError });
  },
  removeImage(e) { if (this._busy) return; const images = this.data.images.filter((item, index) => index !== Number(e.currentTarget.dataset.index)); this.setData({ images, canAddImages: true }); },
  async save() {
    if (this._busy) return;
    if (!this.data.images.length) return wx.showToast({ title: '请先选择图片', icon: 'none' });
    this._busy = true;
    wx.showLoading({ title: '正在保存图片', mask: true });
    let images;
    try {
      images = []; for (const image of this.data.images) images.push(cloud.isRemoteFile(image) ? image : await cloud.persistFile(image, 'photos'));
    } catch (error) {
      wx.hideLoading();
      this._busy = false;
      return cloud.showUploadError(error, '照片上传失败', () => this.save());
    }
    const name = this.data.name.trim();
    const common = { showName: this.data.showName, nameAutoGenerated: !name || this._originalAutoName && name === this._originalPhotoName, folderId: this.data.folderId, campId: this.data.context.campId, stageId: this.data.context.stageId, subcampId: this.data.context.subcampId, activityName: this.data.context.activityName || '', visibility: this.data.visibilityOptions[this.data.visibilityIndex].value, hideUid: this.data.isPublic && this.data.hideUid };
    this._savedPaths = this._savedPaths || new Set();
    this._photoIds = this._photoIds || new Map();
    images.forEach((image, index) => {
      if (!this._photoIds.has(image)) this._photoIds.set(image, `photo-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`);
      if (!this._savedPaths.has(image)) data.stageDraft('photo', Object.assign({}, common, { id: this.data.id || this._photoIds.get(image), image, name: name ? (images.length === 1 ? name : `${name} · ${index + 1}`) : `${this.data.folderName}${index + 1}` }));
    });
    try {
      for (let index = 0; index < images.length; index += 1) {
        const image = images[index];
        if (!this.data.id && this._savedPaths.has(image)) continue;
        wx.showLoading({ title: `保存 ${index + 1}/${images.length}`, mask: true });
        if (!this._photoIds.has(image)) this._photoIds.set(image, `photo-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`);
        await data.savePhotoAsync(Object.assign({}, common, { id: this.data.id || this._photoIds.get(image), image, name: name ? (images.length === 1 ? name : `${name} · ${index + 1}`) : `${this.data.folderName}${index + 1}` }));
        this._savedPaths.add(image);
      }
    } catch (error) { wx.hideLoading(); this._busy = false; return cloud.showUploadError(error, '部分图片未保存，请重试', () => this.save()); }
    this.setData({ images });
    wx.hideLoading();
    this._busy = false;
    wx.showToast({ title: this.data.id || images.length === 1 ? '图片已保存' : `已保存 ${images.length} 张`, icon: 'success' });
    setTimeout(() => wx.navigateBack({ delta: 1 }), 350);
  },
  remove() { wx.showModal({ title: '删除这张图片？', content: '删除后无法恢复，是否继续？', confirmColor: '#C84A3A', success: result => { if (result.confirm) require('../../utils/actions').run(this, () => data.deletePhoto(this.data.id), '图片已删除', () => wx.navigateBack({ delta: 1 })); } }); }
});
