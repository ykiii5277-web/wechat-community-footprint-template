const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.resolve(__dirname, '..');
const { assignPhotoName } = require('../cloudfunctions/hui-api/photo-names');
const context = { campId: 'rural', stageId: 'camper', subcampId: '', activityName: '' };
const copy = value => JSON.parse(JSON.stringify(value));
function namingTests() {
  const folder = { id: 'album', name: '乡村合照' };
  const make = (id, name, extra = {}) => ({ kind: 'photo', contentId: id, payload: Object.assign({ id, folderId: 'album', name }, extra) });
  const records = [make('a', '原有照片'), make('a', '原有照片'), make('b', '乡村合照7'), make('outside', '乡村合照100', { folderId: 'other' })];
  const input = { id: 'new', folderId: 'album', name: '客户端猜测1', nameAutoGenerated: true };
  const named = assignPhotoName(input, folder, records);
  assert.equal(named.name, '乡村合照8'); assert.equal(named.title, named.name); assert.equal(named.albumSequence, 8);
  const repeated = assignPhotoName({ id: 'new', folderId: 'album', name: '', nameAutoGenerated: true }, { name: '相册新名字' }, records, named);
  assert.equal(repeated.name, '乡村合照8', 'retry and album rename must not renumber or silently rename an existing image');
  const custom = assignPhotoName({ id: 'custom', folderId: 'album', name: '我的自定义名称' }, folder, records);
  assert.equal(custom.name, '我的自定义名称'); assert.equal(custom.nameAutoGenerated, false);
  assert.equal(assignPhotoName({ id: 'fresh', folderId: 'album', name: '' }, folder, []).name, '乡村合照1');
}
async function backendTests() {
  const docs = new Map(); let revision = 0, writes = 0, injectConflict = false, securityNames = [];
  docs.set('album', { _id: 'album-doc', ownerOpenid: 'owner', kind: 'album', contentId: 'album', payload: Object.assign({}, context, { id: 'album', name: '我的相册', visibility: 'self' }) });
  const sdk = { init() {}, database: () => ({ command: {} }) };
  const commit = async (owner, jobs, removals, expectedRevision) => {
    if (injectConflict) {
      injectConflict = false; revision++;
      docs.set('concurrent', { _id: 'concurrent-doc', ownerOpenid: owner, kind: 'photo', contentId: 'concurrent', payload: Object.assign({}, context, { folderId: 'album', name: '我的相册5', albumSequence: 5 }) });
      throw new Error('CONTENT_CONFLICT');
    }
    if (expectedRevision != null && expectedRevision !== revision) throw new Error('CONTENT_CONFLICT');
    jobs.forEach(job => { writes++; job.record._id = `${job.record.contentId}-doc`; docs.set(job.record.contentId, copy(job.record)); }); revision++;
  };
  const module = { exports: {} };
  vm.runInNewContext(fs.readFileSync(path.join(root, 'cloudfunctions/hui-api/index.js'), 'utf8') + `
    ownProfile = globalThis.profileForTest; findContent = globalThis.findForTest; ownerContentRecords = globalThis.recordsForTest;
    checkSubmission = globalThis.checkForTest; profilesByOpenids = async () => ({ owner: { uid: '7654321', name: '当前昵称' } });
    loadPublicContents = async () => (await ownerContentRecords('owner')).data.filter(item => item.visibility === 'public');
    resolveSharedContentList = async list => list;
    module.exports = { upsertContent, publicList };
  `, {
    module, exports: module.exports, process, Buffer,
    profileForTest: async () => ({ uid: '7654321', contentRevision: revision }),
    findForTest: async (owner, kind, id) => { const doc = docs.get(id); return doc && doc.kind === kind ? copy(doc) : null; },
    recordsForTest: async () => ({ data: Array.from(docs.values()).map(copy) }),
    checkForTest: async (owner, names) => { securityNames.push(...names); },
    require(name) {
      if (name === 'wx-server-sdk') return sdk;
      if (name === './content-manager') return { createManager: () => ({ commit }) };
      if (name === './media-files') return Object.assign({}, require('../cloudfunctions/hui-api/media-files'), { storedFileSize: async () => 1024 });
      return require(name.startsWith('.') ? path.join(root, 'cloudfunctions/hui-api', name) : name);
    }
  });
  const api = module.exports;
  const upload = (id, extra = {}) => ({ kind: 'photo', item: Object.assign({}, context, { id, folderId: 'album', image: `cloud://${id}`, visibility: 'public', name: '错误的预分配名字1', nameAutoGenerated: true, showName: false }, extra) });
  await assert.rejects(api.upsertContent('owner', { kind: 'album', item: { id: 'empty', name: '  ' } }), /ALBUM_NAME_REQUIRED/);
  assert.equal(writes, 0);
  const one = await api.upsertContent('owner', upload('one')); assert.equal(one.name, '我的相册1');
  const two = await api.upsertContent('owner', upload('two')); assert.equal(two.name, '我的相册2', 'a later batch continues album numbering');
  const repeat = await api.upsertContent('owner', upload('one')); assert.equal(repeat.name, one.name); assert.equal(writes, 2, 'lost receipt retry must not rewrite or duplicate a saved photo');
  injectConflict = true;
  const afterRace = await api.upsertContent('owner', upload('three')); assert.equal(afterRace.name, '我的相册6', 'concurrent numbering retries with a fresh server revision');
  await api.upsertContent('owner', upload('four', { name: '用户自己命名', nameAutoGenerated: false, hideUid: true }));
  assert(securityNames.includes('我的相册6'), 'generated names must pass the same text safety checks');
  const list = await api.publicList({ range: 'latest' });
  const shown = list.items.find(item => item.id === 'one'), hidden = list.items.find(item => item.id === 'four');
  assert.equal(shown.title, '我的相册1', 'showName=false must not suppress a public photo title');
  assert.equal(shown.summary, 'UID：7654321'); assert.equal(hidden.title, '用户自己命名'); assert.equal(hidden.summary, ''); assert.equal(hidden.ownerUid, '');
  const search = await api.publicList({ keyword: '我的相册1' }); assert.equal(search.total, 1);
}
function page(file, dependencies, wx) {
  let value;
  vm.runInNewContext(fs.readFileSync(path.join(root, file), 'utf8'), { Page: item => { value = item; }, wx, require: name => dependencies[name] || {} });
  value.data = copy(value.data); value.setData = changes => Object.assign(value.data, changes); return value;
}
