async function lostReceiptTest() {
  const { createSync } = require('../utils/content-sync');
  const storage = new Map();
  global.wx = { getStorageSync: key => storage.get(key), setStorageSync: (key, value) => storage.set(key, copy(value)), removeStorageSync: key => storage.delete(key) };
  const keys = Object.fromEntries(['profile', 'photos', 'growth', 'works', 'companions', 'folders', 'activities'].map(key => [key, key]));
  const remote = { profile: { uid: '1234567', syncVersion: 2 }, photos: [], growth: [], works: [], companions: [], albums: [{ id: 'album', name: '云端相册' }], activities: [] };
  const cloud = { CLOUD_ENV_ID: 'names-test', isRemoteFile: () => true, getOwnState: async () => copy(remote), upsertContent: async (kind, item) => {
    remote.photos = [Object.assign({}, item, { name: '云端相册6', nameAutoGenerated: true, albumSequence: 6 })];
    return { error: 'NETWORK', message: 'lost receipt' };
  } };
  const sync = createSync({ cloud, keys, init() {}, today: () => '2026.11.02', normalizeActivityName: value => value || '', getProfile: () => wx.getStorageSync('profile') || {} });
  sync.bindCloudAccount(remote.profile); await sync.hydrateOwnCloudState();
  await assert.rejects(sync.savePhotoAsync({ id: 'lost', folderId: 'album', name: '预分配名1', nameAutoGenerated: true, image: 'cloud://image' }), /lost receipt/);
  await sync.hydrateOwnCloudState();
  assert.equal(sync.getSyncStatus().items.length, 0, 'server-assigned names must reconcile after a lost acknowledgement');
  assert.equal(wx.getStorageSync('photos')[0].name, '云端相册6');
}
Promise.resolve().then(namingTests).then(backendTests).then(frontendTests).then(lostReceiptTest).then(() => console.log('required album names, sequential server photo names, idempotent/concurrent/lost-receipt retries, public titles/UID privacy and legacy display passed')).catch(error => { console.error(error); process.exitCode = 1; });
